"""Rebuild snippets/claude-code-sessions-data.jsx from the claude_code example's cached answers.

    uv run --extra sql python docs-site/make_claude_code_data.py     # from the repo root; asks nothing (HUNCH_MAX_COST=0)

Needs the public Trace Commons sessions (CC BY 4.0) in prototype/examples/claude_code/.cache (see NOTICE.md there).

TURNS: a few of the 60 turns the review panel graded, as the question saw them (redacted and clipped by the spec),
with the end of the agent's reply trimmed for the page, the question's answer, how sure it was, and the panel's votes.
REVIEWED: the 60 graded turns as [the answer cleared act (0/1), the answer matched the panel (0/1)]: the result figure.
"""
import csv
import json
import os
from collections import Counter
from pathlib import Path

os.environ["HUNCH_MAX_COST"] = "0"
import hunch.core as H  # noqa: E402

EXAMPLE = Path("prototype/examples/claude_code")
PANEL = Path("prototype/review_panel/claude_code")
TURNS = {  # turn id: why it is here
    "4222016d#1": "The developer moves straight on to the next milestones. Nobody says thanks, "
                  "but building on the result is accepting it.",
    "d4c4d47d#15": "Nothing is broken. The developer wants a different layout, which is a change of approach.",
    "47d9fc04#47": "The developer hasn't tried it yet, so the next message can't say whether it worked.",
    "09d9abe9#7": "The icon appears, in the wrong place. The panel called that a failure; the question said "
                  "it worked, fairly sure. It is one of its six mistakes on the 60 graded turns.",
}
REPLY_CHARS = 360


def answers(path):
    res = H.execute(H.load_project(path))["outcome"]
    return {it["row"]["id"]: H.decide(res["answers"][it["key"]])[:2] for it in res["items"]}, res["spec"]


def tail(text, n=REPLY_CHARS):
    """The last paragraphs of the reply that fit in n characters, without markdown bold."""
    paras, out = text.replace("**", "").strip().split("\n\n"), []
    for p in reversed(paras):
        if out and len(p) + sum(map(len, out)) > n:
            break
        out.insert(0, p.strip())
    s = "\n\n".join(out)
    s = s if len(s) <= n else "…" + s[-n:].split(" ", 1)[1]
    return s if len(out) == len(paras) else "… " + s


ans, spec = answers(EXAMPLE / "outcome.yml")
act = spec["questions"]["outcome"]["act"]
rows = {r["id"]: H.state_of(spec, r) for r in H.rows(spec)}
ids = json.load(open(PANEL / "key/map.json"))  # packet number -> turn id
votes = {tid: Counter(json.load(open(PANEL / f"answers/{rev}.json"))[int(n) - 1]["outcome"]
                      for rev in ["opus", "sonnet_a", "sonnet_b"]) for n, tid in ids.items()}
gold = {r["row_id"]: r["label"] for r in csv.DictReader(open(EXAMPLE / "outcome.reviews.csv"))
        if r["verdict"] == "labeled"}

turns = []
for tid, why in TURNS.items():
    s, (label, p) = rows[tid], ans[tid]
    panel, n = votes[tid].most_common(1)[0]
    assert panel == gold[tid], tid
    turns.append({"request": s["request"], "reply": tail(s["final_reply"]), "next": s["next_message"],
                  "hunch": label, "p": round(p, 2), "panel": panel, "votes": n, "why": why})
    print(f"{tid}: hunch {label} {p:.2f}, panel {panel} ({n} of 3), reply {len(s['final_reply'])} -> {len(turns[-1]['reply'])}")

reviewed = sorted([[int(ans[t][1] >= act), int(ans[t][0] == g)] for t, g in gold.items()], key=lambda x: (-x[0], -x[1]))
sure = [r for r in reviewed if r[0]]
print(f"{len(reviewed)} graded: {sum(r[1] for r in reviewed)} right; {len(sure)} above act={act}, "
      f"{sum(1 - r[1] for r in sure)} of them wrong")

dest = Path(__file__).parent / "snippets" / "claude-code-sessions-data.jsx"
dest.write_text("// Generated by docs-site/make_claude_code_data.py from prototype/examples/claude_code (Trace Commons "
                "agent traces, CC BY 4.0). Do not edit.\n"
                f"export const TURNS = {json.dumps(turns, ensure_ascii=False, separators=(',', ':'))};\n"
                f"export const REVIEWED = {json.dumps({'act': act, 'rows': reviewed}, separators=(',', ':'))};\n")
print(f"-> {dest} ({dest.stat().st_size // 1024} KB)")
