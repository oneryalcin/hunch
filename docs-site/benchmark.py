"""The benchmark page, generated from the batteries' receipts: every battery × every engine it was measured with.

    uv run docs-site/benchmark.py          # write docs-site/reference/benchmark.mdx
    uv run docs-site/benchmark.py --check  # fail if the page doesn't match the receipts (make check runs this)

A receipt is `results.json` (the spec's own engine) or `results__<engine>.json` (`hunch test --model X --receipt`)
beside a battery's spec. Nothing here is typed by hand: to add an engine, measure it and commit its receipt.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
RECIPES = HERE.parent / "src" / "hunch" / "recipes"
PAGE = HERE / "reference" / "benchmark.mdx"


def pct(x):
    return "–" if x is None else f"{x:.1%}"


def num(x):
    return "–" if x is None else f"{x:.3f}"


def page() -> str:
    out = ["""---
title: "Benchmark"
description: "Every battery, measured with every engine it has a receipt for: generated from the receipts, not written by hand."
---

{/* Generated by docs-site/benchmark.py from the receipts beside each battery. Do not edit: measure, commit the receipt, regenerate. */}

Each battery ships its labelled rows, and a receipt for each engine it was measured with (`hunch test --model <engine> --receipt`). This page is those receipts side by side. A row is one engine answering one question on the battery's own rows; accuracy and AUROC are against the battery's gold. An engine's number here is on this battery's data: measure it on yours before choosing.

`act` bars are set for the spec's own engine; another engine's probabilities mean something else, so its acting numbers aren't comparable and are left out.
"""]
    for folder in sorted(p for p in RECIPES.iterdir() if (p / "results.json").exists()):
        receipts = sorted(folder.glob("results*.json"), key=lambda p: (p.name != "results.json", p.name))
        docs = [json.loads(p.read_text()) for p in receipts]
        rows_of = {}
        out.append(f"## `{folder.name.replace('_', '-')}`\n")
        readme = (folder / "README.md").read_text().splitlines()
        out.append(next((line for line in readme[1:] if line.strip()), "") + "\n")
        out.append("| Engine | Question | Rows with gold | Accuracy | AUROC | Calibration error | Battery's tests |")
        out.append("| --- | --- | --- | --- | --- | --- | --- |")
        for doc in docs:
            for j in doc["judgments"].values():
                for qname, q in j["questions"].items():
                    if not (q.get("gold") or {}).get("rows"):
                        continue
                    rows_of[qname] = q["gold"]["rows"]
                    checks = q.get("checks", [])
                    tests = "–" if not checks else "pass" if all(c["passed"] for c in checks) else \
                        "fail: " + ", ".join(c["check"] for c in checks if not c["passed"])
                    acc = (q.get("accuracy") or {}).get("value")
                    out.append(f"| `{j['model']}` | `{qname}` | {q['gold']['rows']} | {pct(acc)} | "
                               f"{num(q.get('auroc'))} | {num(q.get('calibration_error'))} | {tests} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


if __name__ == "__main__":
    text = page()
    if "--check" in sys.argv:
        if not PAGE.exists() or PAGE.read_text() != text:
            sys.exit(f"{PAGE.relative_to(HERE.parent)} doesn't match the receipts: run `uv run docs-site/benchmark.py`")
        print("benchmark: the page matches the receipts")
    else:
        PAGE.write_text(text)
        print(f"wrote {PAGE.relative_to(HERE.parent)}")
